def test_background_step_execution_auto_approves_and_unlocks_next_step(client, monkeypatch):
    task = create_task(client)
    detail = generate_plan(client, task["id"])
    approve_plan(client, task["id"])
    first_step, second_step = detail["steps"]

    def fake_execute_step(task_model, step_model, run_input, previous_steps):
        assert task_model.id == task["id"]
        assert step_model.id == first_step["id"]
        assert run_input == {"note": "attempt"}
        assert previous_steps == []
        return {"summary": "LLM finished step one", "details": "Generated by test"}

    monkeypatch.setattr(step_execution_service, "execute_step", fake_execute_step)
    run = create_run(client, task["id"], first_step["id"], "agent")
    assert run["status"] == "running"

    runs = client.get(f"/tasks/{task['id']}/steps/{first_step['id']}/runs").json()
    completed_run = runs[0]
    assert completed_run["status"] == "accepted"
    assert completed_run["output"]["summary"] == "LLM finished step one"

    detail = client.get(f"/tasks/{task['id']}").json()
    approved_step = next(step for step in detail["steps"] if step["id"] == first_step["id"])
    assert approved_step["status"] == "approved"
    assert approved_step["approved_run_id"] == run["id"]
    assert detail["task"]["status"] == "planned"
    assert detail["current_pointer"] == {
        "task_id": task["id"],
        "step_id": second_step["id"],
        "run_id": None,
        "capability_invocation_id": None,
    }
    start_actions = [action for action in detail["next_actions"] if action["action_type"] == "start_step_run"]
    assert len(start_actions) == 1
    assert start_actions[0]["target"] == {"task_id": task["id"], "step_id": second_step["id"]}


