def test_auto_run_from_step_runs_branch_on_completed_task(client, monkeypatch):
    task = create_task(client)
    detail = generate_plan(client, task["id"])
    approve_plan(client, task["id"])
    first_step, second_step = detail["steps"]

    for step in [first_step, second_step]:
        run = create_run(client, task["id"], step["id"], "human")
        submit_run(client, task["id"], step["id"], run["id"])
        response = client.post(f"/tasks/{task['id']}/steps/{step['id']}/runs/{run['id']}/review", json={"decision": "approved"})
        assert response.status_code == 200, response.text

    detail = client.get(f"/tasks/{task['id']}").json()
    assert detail["task"]["status"] == "completed"
    branch_response = client.post(
        f"/tasks/{task['id']}/steps/{first_step['id']}/rerun",
        json={"executor_type": "agent", "input": {}, "change_request": "Run branch from here"},
    )
    assert branch_response.status_code == 200, branch_response.text
    branch_step_id = branch_response.json()["forked_step_id"]
    detail = client.get(f"/tasks/{task['id']}").json()
    branch_step = next(step for step in detail["steps"] if step["id"] == branch_step_id)
    branch_successor_id = branch_step["next_step_ids"][0]
    seen_steps = []

    def fake_execute_step(task_model, step_model, run_input, previous_steps):
        seen_steps.append(step_model.id)
        assert run_input == {"instruction": "branch", "auto_run": True, "auto_run_start_step_id": branch_step_id}
        return {"summary": f"completed {step_model.title}", "details": "Generated by test"}

    monkeypatch.setattr(step_execution_service, "execute_step", fake_execute_step)
    response = client.post(
        f"/tasks/{task['id']}/steps/{branch_step_id}/auto-run",
        json={"executor_type": "agent", "input": {"instruction": "branch"}},
    )
    assert response.status_code == 200, response.text
    assert response.json()["started"] is True

    detail = client.get(f"/tasks/{task['id']}").json()
    branch_step = next(step for step in detail["steps"] if step["id"] == branch_step_id)
    branch_successor = next(step for step in detail["steps"] if step["id"] == branch_successor_id)
    assert branch_step["status"] == "approved"
    assert branch_successor["status"] == "approved"
    assert seen_steps == [branch_step_id, branch_successor_id]


